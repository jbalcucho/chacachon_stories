/**
 * Obtiene connection strings de Neon vía neonctl y escribe .env.local.
 * Requiere: neonctl autenticado (npx neonctl auth).
 *
 * Antes de ejecutar, edita PROJECT_ID, ORG_ID y DB_NAME abajo.
 */

import { execSync } from "child_process";
import fs from "fs";

const PROJECT_ID = "withered-cake-28248560";
const ORG_ID = "org-tiny-salad-00933340";
const DB_NAME = "chacachon";

function neonConnectionString(pooled) {
  const args = [
    "neonctl@latest",
    "connection-string",
    "--project-id",
    PROJECT_ID,
    "--org-id",
    ORG_ID,
    "--database-name",
    DB_NAME,
    "--output",
    "json",
  ];
  if (pooled) args.push("--pooled");
  const raw = execSync(`npx ${args.join(" ")}`, { encoding: "utf8" }).trim();
  if (raw.startsWith("postgresql://")) return raw;
  const parsed = JSON.parse(raw);
  return parsed.connection_uri ?? parsed.uri ?? raw;
}

const direct = neonConnectionString(false);
let pooled = neonConnectionString(true);
if (!pooled.includes("pgbouncer")) {
  pooled += `${pooled.includes("?") ? "&" : "?"}pgbouncer=true&connection_limit=1`;
}

const envContent = [
  "# Auto-generated by scripts/fetch-neon-env.mjs — do not commit",
  `DATABASE_URL="${pooled}"`,
  `DIRECT_URL="${direct}"`,
  "",
].join("\n");

fs.writeFileSync(".env", envContent);
fs.writeFileSync(".env.local", envContent);

console.log("✓ Wrote .env and .env.local with Neon connection strings for chacachon");
